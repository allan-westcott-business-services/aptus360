-- ════════════════════════════════════════════════════════════════
-- 0081 — the heat pump register
--
-- 1,255 models from the MCS register, with the rated load of each. The
-- table has existed since 0002 holding nothing but a name, which is not
-- enough to identify a unit or to size anything.
--
-- Three things about the data decided the shape.
--
--   Model is not unique. 150 make-and-model pairs appear more than once,
--   and 91 of those carry different loads — an Airwell AW-WHPMA08-H91 is
--   listed at both 3.43 and 6.42 kVA under separate register entries. So
--   the UNIQUE on Model has to go, or the import rejects a fifth of the
--   file, and Register_Number becomes the key. It is unique across all
--   1,255 rows and is what the register itself identifies a unit by.
--
--   Model_Reference is therefore not decoration: it is the only thing
--   distinguishing two rows that otherwise read identically. Any picker
--   showing make and model alone will show duplicates that cannot be
--   told apart.
--
--   The source has non-breaking spaces trailing many of the model names.
--   They are stripped here rather than on read, so a search for a model
--   matches what is on screen.
--
-- Rated_Power_kVA is the figure that should eventually replace the 2.2
-- placeholder 0080 put on every plot: the load a plot draws follows from
-- the unit fitted to it. That connection is not made here — it changes
-- how every plot is costed, and is worth doing deliberately.
-- ════════════════════════════════════════════════════════════════

ALTER TABLE "Heat_Pump_Model"
  ADD COLUMN IF NOT EXISTS "Register_Number"  text,
  ADD COLUMN IF NOT EXISTS "Make"             text,
  ADD COLUMN IF NOT EXISTS "Model_Reference"  text,
  ADD COLUMN IF NOT EXISTS "Rated_Power_kVA"  numeric,
  ADD COLUMN IF NOT EXISTS "Is_Active"        boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS "Created_At"       timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS "Updated_At"       timestamptz NOT NULL DEFAULT now();

-- Model repeats legitimately, so it cannot be the key.
ALTER TABLE "Heat_Pump_Model" DROP CONSTRAINT IF EXISTS "Heat_Pump_Model_Model_key";

CREATE UNIQUE INDEX IF NOT EXISTS heat_pump_register_uniq
  ON "Heat_Pump_Model" ("Register_Number") WHERE "Register_Number" IS NOT NULL;

CREATE INDEX IF NOT EXISTS heat_pump_make_model_idx
  ON "Heat_Pump_Model" ("Make", "Model");


