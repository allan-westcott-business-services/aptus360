-- 0200 — a site can be fed from more than one side, electric included
--
-- 0157 dropped the one-POC-per-utility rule for gas and water and kept
-- it for electric, on the argument that the electric POC feeds the
-- substation and the substation feeds every circuit — so a second POC
-- was a kind of scheme the application did not draw, and a constraint
-- that refuses it was better than a drawing that half-supports it.
--
-- The application draws it now. Each electric origin serves the trench
-- network it stands on: buildFeederModel roots every circuit at the
-- origin on its own network (chosen by the component the circuit's
-- seeds stand on), the circuit report measures each meter from the
-- origin that reaches it, the levels check reads source impedance and
-- the declared upstream volt drop from each circuit's own POC, and two
-- origins standing on ONE network is refused by name where it is
-- detected — at build time, where the drawing shows which trenches to
-- split.
--
-- So the index would now refuse exactly the drawing the rest of the
-- code supports, and the error it raised — a bare unique-violation
-- naming gis_poc_one_electric — reached the canvas as a database
-- message rather than as anything a designer could act on. The rule
-- the index enforced has not been weakened; it has moved to the one
-- place that can tell a second incomer from a second network, which a
-- count of rows never could.
--
-- Nothing else changes: gas and water POCs were already several.
-- ════════════════════════════════════════════════════════════════

DROP INDEX IF EXISTS gis_poc_one_electric;


