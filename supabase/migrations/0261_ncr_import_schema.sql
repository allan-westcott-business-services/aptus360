-- For whoever writes the import that follows this
--
-- Three things were found by loading all 1,797 rows against this
-- schema rather than by reading it:
--
--   NCR_ID is GENERATED ALWAYS AS IDENTITY. Keeping the original ids
--   — which NCR_Attachment.NCR_ID requires — needs
--   OVERRIDING SYSTEM VALUE on the insert.
--
--   And then the identity sequence must be moved on:
--
--     SELECT setval(pg_get_serial_sequence('"NCR"', 'NCR_ID'),
--                   (SELECT max("NCR_ID") FROM "NCR"));
--
--   Without it the sequence sits at 1 after the import and the next
--   NCR raised in the application collides with an imported row. It
--   reads as the app being broken rather than as an import that was
--   not finished.
--
--   NCR_Reference is UNIQUE (ncr_reference_once) and the export has
--   one collision: NCR11444 is used by NCR_ID 1341 and 1342, two
--   different NCRs on different sites. One needs a distinct
--   reference before the import will run at all.
--
-- And the status must be matched by NAME. 'With Developer' takes
-- whatever id the sequence gives it, which is only 4 by coincidence.
-- ════════════════════════════════════════════════════════════════
