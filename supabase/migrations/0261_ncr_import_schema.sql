-- ════════════════════════════════════════════════════════════════
-- 0261 — what the NCR import needs that this database has not got
--
-- The non-compliance reports are being brought over from the original
-- system. Four things are missing, and each was decided on rather than
-- assumed:
--
--   1. Business_Unit — the column exists on NCR, the table does not.
--   2. NCR.Address_Raw — 1,608 of the 1,797 rows carry a site address
--      and there is nowhere to put it.
--   3. Auditor_Type 'Aptus' — four NCRs are Aptus auditing Aptus, and
--      the check constraint allows only DNO and IDNO.
--   4. NCR_Attachment — 98 rows, no table.
--
-- Nothing here imports anything. This only makes room.
-- ════════════════════════════════════════════════════════════════


-- ── 1. Business_Unit ──
--
-- One row, "Operations", on every NCR in the export. A table for a
-- single constant value looks like overkill, and it is not: the column
-- is already on NCR and has been pointing at nothing, so a reader
-- cannot tell whether Business_Unit_ID 1 means Operations, means
-- nothing, or means a table somebody forgot to create. Now it means
-- Operations, and a second unit can be added without a migration.

CREATE TABLE IF NOT EXISTS "Business_Unit" (
  "Business_Unit_ID" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Business_Unit"    text    NOT NULL UNIQUE,
  "Sort_Order"       integer NOT NULL DEFAULT 0,
  "Is_Active"        boolean NOT NULL DEFAULT true
);

INSERT INTO "Business_Unit" ("Business_Unit_ID", "Business_Unit", "Sort_Order")
VALUES (1, 'Operations', 1)
ON CONFLICT ("Business_Unit") DO NOTHING;

/* The identity sequence is told where the hand-set id leaves off, or
   the next insert collides with 1. Skipping this is how a seeded table
   fails on its second row, months later, for somebody else. */
SELECT setval(pg_get_serial_sequence('"Business_Unit"', 'Business_Unit_ID'),
              GREATEST((SELECT max("Business_Unit_ID") FROM "Business_Unit"), 1));

/* The foreign key NCR has been missing. NOT VALID so it binds new and
   changed rows without scanning what is already there — NCR is empty
   today, but this migration must also be safe to run on a database
   where it is not. */
ALTER TABLE "NCR"
  DROP CONSTRAINT IF EXISTS ncr_business_unit_fk;
ALTER TABLE "NCR"
  ADD CONSTRAINT ncr_business_unit_fk
  FOREIGN KEY ("Business_Unit_ID") REFERENCES "Business_Unit"("Business_Unit_ID")
  NOT VALID;


-- ── 2. The address the NCR was raised against ──
--
-- Kept as raw text, exactly as the original system holds it, rather
-- than parsed into the address columns Project already has.
--
-- Two reasons. It is what somebody typed on the day and is evidence
-- about that NCR, not a current address to maintain. And 66 of the
-- 1,797 NCRs have no contract at all, so for those it is the only
-- location there is — parsing it into a project that does not exist
-- would lose it.

ALTER TABLE "NCR" ADD COLUMN IF NOT EXISTS "Address_Raw" text;

COMMENT ON COLUMN "NCR"."Address_Raw" IS
  'The site address as recorded in the original system, verbatim. '
  'The project link is the authority on where an NCR happened; this is '
  'what was written down at the time, and the only location for the 66 '
  'NCRs that carry no contract.';


-- ── 3. The auditor is an organisation ──
--
-- The columns were Auditor_DNO_ID and Auditor_IDNO_ID, pointing at the
-- DNO and IDNO shim tables. That cannot describe this data.
--
-- 889 of the NCRs are Water and carry Auditor_Type = 'DNO'. A DNO
-- distributes electricity; it cannot have raised a water NCR. The old
-- system used "DNO" to mean the incumbent for whatever utility and
-- "IDNO" to mean the independent one — IWUs and IGTs included, which
-- is what they were called at the time. So old DNO 3 is United
-- Utilities (846 NCRs), old DNO 1 is Cadent, and old IDNO 4 is GTC.
--
-- Matched to organisations by name, those thirteen operators land on
-- five different roles: wu, iwu, gt, idno and dno. Two columns named
-- after two of those five cannot hold them.
--
-- So the auditor is an Organisation, as it already is on
-- Project_Scope, POC_Application, Plot_Utility, AV_Agreement and six
-- others. The role is read from Organisation_Role rather than written
-- on the NCR, which is what stops this drifting again: an operator
-- that gains a role gains it everywhere at once.
--
-- The two old columns are dropped rather than left. NCR is empty, so
-- nothing is lost, and a column that cannot be filled correctly is a
-- column somebody will fill incorrectly.

ALTER TABLE "NCR" ADD COLUMN IF NOT EXISTS "Auditor_Organisation_ID" bigint;

ALTER TABLE "NCR" DROP CONSTRAINT IF EXISTS ncr_auditor_organisation_fk;
ALTER TABLE "NCR"
  ADD CONSTRAINT ncr_auditor_organisation_fk
  FOREIGN KEY ("Auditor_Organisation_ID") REFERENCES "Organisation"("Organisation_ID");

/* Auditor_Type survives, with the only distinction the organisation
   cannot make: whether anybody outside raised it.

   Four NCRs are Aptus auditing Aptus — a gas duct in the wrong colour,
   a competency passport, an excavator's brakes, missing PAT labels.
   Those are the HSQE process working, and worth counting apart from
   the 149 that simply never had an auditor recorded.

   'DNO' and 'IDNO' are gone from the vocabulary. They described a
   world with two kinds of operator, and there are five. */
ALTER TABLE "NCR" DROP CONSTRAINT IF EXISTS "NCR_Auditor_Type_check";
ALTER TABLE "NCR" DROP CONSTRAINT IF EXISTS ncr_auditor_matches_type;

ALTER TABLE "NCR" ADD CONSTRAINT "NCR_Auditor_Type_check"
  CHECK ("Auditor_Type" = ANY (ARRAY['Operator'::text, 'Aptus'::text]));

/* An outside operator means an organisation; Aptus means none. A row
   claiming an operator with nobody named is the fault this pairing
   exists to stop — it reads on screen as "audited by —". */
ALTER TABLE "NCR" ADD CONSTRAINT ncr_auditor_matches_type CHECK (
     ("Auditor_Type" = 'Operator' AND "Auditor_Organisation_ID" IS NOT NULL)
  OR ("Auditor_Type" = 'Aptus'    AND "Auditor_Organisation_ID" IS NULL)
  OR ("Auditor_Type" IS NULL      AND "Auditor_Organisation_ID" IS NULL)
);

ALTER TABLE "NCR" DROP COLUMN IF EXISTS "Auditor_DNO_ID";
ALTER TABLE "NCR" DROP COLUMN IF EXISTS "Auditor_IDNO_ID";

COMMENT ON COLUMN "NCR"."Auditor_Organisation_ID" IS
  'The organisation that raised the NCR. Which capacity they raised it '
  'in — wu, iwu, gt, idno, dno — is read from Organisation_Role, not '
  'stored here: an operator plays several and gains new ones.';


-- ── 4. NCR_Attachment ──
--
-- 98 rows in the export: PDFs and saved Outlook messages, mostly the
-- action-status emails the operators send.
--
-- Storage_Path is a path inside a storage bucket, not a URL, and the
-- FILES are a separate job from these rows. A row whose file was never
-- copied across is a broken link, which is worse than no row — so the
-- import of this table waits on the files, and this migration only
-- builds the shelf.

CREATE TABLE IF NOT EXISTS "NCR_Attachment" (
  "NCR_Attachment_ID" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "NCR_ID"            bigint NOT NULL,
  "Attachment_Type"   text,
  "File_Name"         text   NOT NULL,
  /* Where the file sits in the bucket. Unique, because two rows
     pointing at one file means deleting one attachment breaks the
     other, and nothing in the application would say why. */
  "Storage_Path"      text   NOT NULL UNIQUE,
  "Mime_Type"         text,
  "File_Size"         bigint,
  "Uploaded_By"       bigint,
  "Created_At"        timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT ncr_attachment_ncr_fk FOREIGN KEY ("NCR_ID")
    REFERENCES "NCR"("NCR_ID") ON DELETE CASCADE,
  /* Not cascading. A person leaving must not delete the record of what
     they attached. */
  CONSTRAINT ncr_attachment_person_fk FOREIGN KEY ("Uploaded_By")
    REFERENCES "Person"("Person_ID") ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS ncr_attachment_ncr_idx
  ON "NCR_Attachment" ("NCR_ID");

COMMENT ON COLUMN "NCR_Attachment"."Storage_Path" IS
  'Path within the storage bucket, as the original system wrote it: '
  '<NCR_ID>/<epoch-ms>-<filename>. Not a URL.';

/* RLS on with no policy, as every other table in this database has it:
   nothing reads this but the endpoints, which hold the service key. */
ALTER TABLE "NCR_Attachment" ENABLE ROW LEVEL SECURITY;


-- ── 5. The one status the export has and this database has not ──
--
-- Open, On Hold and Closed are already here and already agree by name.
-- Sort_Order 25 is the original system's, kept so the dropdown reads
-- in the order people are used to.

INSERT INTO "NCR_Status" ("NCR_Status", "Sort_Order", "Is_Active")
SELECT 'With Developer', 25, true
WHERE NOT EXISTS (
  SELECT 1 FROM "NCR_Status" WHERE lower("NCR_Status") = lower('With Developer')
);


-- ── 6. The four foreign keys NCR never had ──
--
-- NCR carries Region_ID, Sub_Region_ID, Project_ID and
-- Owner_Person_ID, and not one of them is a foreign key. Elsewhere in
-- this database those same columns are: 61 tables point at Person, 23
-- at Project, 7 at Region. NCR is the exception, and it is an
-- oversight rather than a decision — there is nothing about an NCR
-- that makes its region more free-form than a project's.
--
-- It matters most right now. The import renumbers every region (old
-- Region 1 was Midlands, here Region 1 is North West) and renumbers
-- every person (old Person 23 is Laura Cassidy, here Person 23 is Ben
-- Mckay). With no foreign key, a mistake in either map writes a wrong
-- id in silence and the screen simply shows the wrong name. With
-- these, it stops.
--
-- NCR is empty, so this is the one moment they cost nothing to add.

ALTER TABLE "NCR" DROP CONSTRAINT IF EXISTS ncr_region_fk;
ALTER TABLE "NCR"
  ADD CONSTRAINT ncr_region_fk
  FOREIGN KEY ("Region_ID") REFERENCES "Region"("Region_ID");

ALTER TABLE "NCR" DROP CONSTRAINT IF EXISTS ncr_sub_region_fk;
ALTER TABLE "NCR"
  ADD CONSTRAINT ncr_sub_region_fk
  FOREIGN KEY ("Sub_Region_ID") REFERENCES "Sub_Region"("Sub_Region_ID");

/* SET NULL, not CASCADE. 66 of the NCRs have no project at all, so an
   NCR is not a child of one — and Address_Raw still says where it
   happened. A project being deleted must not take the record of what
   went wrong on it. */
ALTER TABLE "NCR" DROP CONSTRAINT IF EXISTS ncr_project_fk;
ALTER TABLE "NCR"
  ADD CONSTRAINT ncr_project_fk
  FOREIGN KEY ("Project_ID") REFERENCES "Project"("Project_ID") ON DELETE SET NULL;

/* Same as NCR_Attachment.Uploaded_By: a person leaving must not delete
   the NCRs they owned. */
ALTER TABLE "NCR" DROP CONSTRAINT IF EXISTS ncr_owner_person_fk;
ALTER TABLE "NCR"
  ADD CONSTRAINT ncr_owner_person_fk
  FOREIGN KEY ("Owner_Person_ID") REFERENCES "Person"("Person_ID") ON DELETE SET NULL;


